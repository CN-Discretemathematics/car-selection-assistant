"""卡片上「更新」日期的**单一口径**。

## 为什么要有这个 module

2026-10-21 用户实测（生产）：「全部车型」页的卡片写着

    2026-09 销量 50,359 辆（榜单口径）      更新：2026-08-29

⇒ **自相矛盾**：销量是 9 月的，日期却停在 8-29。

根因不是日期算错，而是**两个页面用了两个不同的字段**，而标签都是「更新：」：

| 页面 | 修之前取的日期 |
| --- | --- |
| 首页 / 销量榜（`app/sales/router.py`） | `sales.last_verified_at or series.last_verified_at`（**销量记录**的核验日） |
| 全部车型页（`app/vehicles/router.py`） | 只有 `series.last_verified_at`（**车系自己**的核验日，**早于**它显示的销量月份） |

生产实测：1102 个在售车系里有 **491 个**的「更新」日期早于它显示的销量月份。

⇒ 口径统一成「**销量记录的核验日优先**，没有销量才用车系的」，
三个地方（首页卡 / 列表卡 / 详情页）**共用这一个函数**——
「同一件事写多遍必然漂移」，口径只写一遍。
"""
from __future__ import annotations

from datetime import datetime


def data_freshness(
    *, series_verified_at: datetime | None, sales_verified_at: datetime | None
) -> datetime | None:
    """卡片上的「更新」该取哪个日期。

    规则：**销量记录的核验日优先**；没有销量（或销量没核验日）才用车系自己的。

    为什么销量优先：卡片上最显眼、也最容易被当成「这份数据是什么时候的」的事实
    是**销量**（带月份）⇒ 「更新」必须与它**同期或更晚**，
    否则用户会看到「9 月的销量 + 8-29 的更新」这种自相矛盾的组合。

    ⚠️ 别把它改成「取两者较新的」：车系的核验日与销量的核验日**不是同一批数据**
    （车系字段还覆盖参数、价格区间等），取较新会让「更新」随另一批数据跳动 ⇒
    口径又会漂。
    """
    return sales_verified_at or series_verified_at
